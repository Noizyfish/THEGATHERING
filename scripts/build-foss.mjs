#!/usr/bin/env node
// FOSS GREATEST HITZ — renders empire/foss/{Brewfile,requirements.txt,npm.txt,GREATEST_HITZ.md} from hitz.json.
//   node scripts/build-foss.mjs            write files
//   node scripts/build-foss.mjs --check    exit 1 if any rendered file is stale
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "empire", "foss");
const m = JSON.parse(readFileSync(join(dir, "hitz.json"), "utf8"));
const list = v => (v == null ? [] : Array.isArray(v) ? v : [v]);
const core = m.hitz.filter(h => !h.optional), opt = m.hitz.filter(h => h.optional);

// ── Brewfile ──
const brew = [`# FOSS GREATEST HITZ — generated from empire/foss/hitz.json by scripts/build-foss.mjs. Do not edit.`,
  `# brew bundle --file empire/foss/Brewfile          (core)`,
  `# brew bundle --file empire/foss/Brewfile.optional (optional tier)`, ``];
const taps = new Set();
const brewLines = hs => hs.flatMap(h => [
  ...list(h.install.brew).map(b => { if (b.includes("/")) taps.add(b.split("/").slice(0, 2).join("/")); return `brew "${b}"  # ${h.name} · ${h.license}`; }),
  ...list(h.install.cask).map(c => `cask "${c}"  # ${h.name} · ${h.license}`)]);
const coreLines = brewLines(core), optLines = brewLines(opt);
const tapLines = [...taps].sort().map(t => `tap "${t}"`);
const brewfile = [...brew, ...tapLines, ``, ...coreLines, ``].join("\n");
const brewfileOpt = [`# Optional tier — generated. brew bundle --file empire/foss/Brewfile.optional`, ...optLines, ``].join("\n");

// ── pip / npm ──
const pipLines = hs => hs.flatMap(h => list(h.install.pip).map(p => `${p}  # ${h.name}`));
const req = [`# generated from hitz.json — uv pip install -r empire/foss/requirements.txt`, ...pipLines(core), ``].join("\n");
const reqOpt = [`# optional tier — uv pip install -r empire/foss/requirements.optional.txt`, ...pipLines(opt), ``].join("\n");
const npmLines = hs => hs.flatMap(h => list(h.install.npm).map(p => `${p}  # ${h.name}`));
const npm = [`# generated from hitz.json — scripts/foss install handles these (npm i -g)`, ...npmLines(core), ``].join("\n");
const npmOpt = [`# optional tier — generated`, ...npmLines(opt), ``].join("\n");

// ── GREATEST_HITZ.md ──
const inst = h => Object.entries(h.install).map(([k, v]) => `\`${k}: ${list(v).join(", ")}\``).join(" · ");
const row = h => `| **[${h.name}](${h.url})** | ${h.license}${h.weights ? ` · weights: ${h.weights}` : ""} | ${h.role} | ${inst(h)} | ${h.usedBy.join(", ")} |`;
const tierBlock = t => {
  const hs = m.hitz.filter(h => h.tier === t);
  return [`### ${t.toUpperCase()} — ${m.tiers[t]}`, ``, `| hit | license | role | install | used by |`, `|---|---|---|---|---|`,
    ...hs.filter(h => !h.optional).map(row), ...hs.filter(h => h.optional).map(h => row(h).replace("| **", "| ○ **")), ``];
};
const licenses = {};
for (const h of m.hitz) for (const l of h.license.split(/ \/ | OR /)) licenses[l.trim()] = (licenses[l.trim()] || 0) + 1;
const md = [`# ${m.title}`, ``,
  `> ${m.hitz.length} hits (${core.length} core · ${opt.length} optional ○) across ${Object.keys(m.tiers).length} tiers. One manifest — \`empire/foss/hitz.json\` — renders this page, the Brewfile, requirements and the doctor. Generated by \`scripts/build-foss.mjs\`; edit the JSON, not this file.`, ``,
  `**Why a list?** Sovereignty is a supply chain. Every box RSP's voice passes through — bus, surface, STT, DAW glue, remote, mirror, backup — must be something we can read, fork and run on our own metal. This page is the audit.`, ``,
  `## Rules`, ``, ...m.rules.map(r => `- ${r}`), ``,
  `## One command on GOD`, ``, "```sh", `scripts/foss install            # Homebrew bundle + uv venv + npm globals (core tier)`,
  `scripts/foss install --optional # + TTS research, Ardour, Node-RED, Headscale…`, `scripts/foss check              # doctor: runs every verify, prints ✅/❌ per hit`,
  `scripts/foss licenses           # SPDX histogram`, "```", ``,
  ...Object.keys(m.tiers).flatMap(tierBlock),
  `## Non-FOSS links in the chain (and the exits)`, ``, `| piece | why it's here | FOSS alternative | exit plan |`, `|---|---|---|---|`,
  ...m.nonfoss.map(n => `| **${n.name}** | ${n.why} | ${n.fossAlternative} | ${n.exit} |`), ``,
  `## License histogram`, ``, `| SPDX | hits |`, `|---|---|`,
  ...Object.entries(licenses).sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${n} |`), ``,
  `## Voice-model weights — the legal line`, ``,
  `NOIZYVOX is trained **only** on consent-signed NOIZYSTDZ sessions (\`engine/consent.py\`, scope \`train\`). The TTS *recipes* above are MIT/Apache; their *pretrained weights* are not all commercial-clean (F5-TTS is CC-BY-NC). Rule: fine-tune from scratch or from Apache/MIT weights (Kokoro, Chatterbox) before anything ships to Nicholas, LINA's listeners, or a client.`, ``,
].join("\n");

const out = { "Brewfile": brewfile, "Brewfile.optional": brewfileOpt, "requirements.txt": req, "requirements.optional.txt": reqOpt, "npm.txt": npm, "npm.optional.txt": npmOpt, "GREATEST_HITZ.md": md };
const check = process.argv.includes("--check");
let stale = 0;
for (const [f, body] of Object.entries(out)) {
  const p = join(dir, f);
  if (check) { if (!existsSync(p) || readFileSync(p, "utf8") !== body) { console.error(`stale: empire/foss/${f}`); stale++; } }
  else { writeFileSync(p, body); console.log(`wrote empire/foss/${f}`); }
}
if (stale) process.exit(1);
